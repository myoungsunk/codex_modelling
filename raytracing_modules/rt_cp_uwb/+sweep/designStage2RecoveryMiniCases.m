function [cases, meta] = designStage2RecoveryMiniCases(candidate_ranking_csv, day3_summary_md)
% designStage2RecoveryMiniCases - Day 4 Stage 2 room mini sweep design.
%
% The design translates the Day 3 Stage 1 outcomes into Stage 2 room cases:
%   P1_MAIN : low effective eps proxy + xpol 30-38 + floor/ceiling-like geometry
%   P2_SENS : low effective eps + mid xpol + moderate/high SNR sensitivity band
%   P3_CTRL : high effective eps or wall-dominant negative control
%
% Layout:
%   - 90 baseline coverage cases per room from generateRoomTxRxGrid
%   - 90 targeted cases per room (30 per candidate, 10 points x 3 parameter combos)
%   - total = 540 cases, patch_ffd only

    if nargin < 1 || isempty(candidate_ranking_csv)
        repo_root = fileparts(fileparts(mfilename('fullpath')));
        candidate_ranking_csv = fullfile(repo_root, 'results', 'recovery_mini', 'day3', 'day3_stage1_recovery_mini_candidate_ranking.csv');
    end
    if nargin < 2 || isempty(day3_summary_md)
        repo_root = fileparts(fileparts(mfilename('fullpath')));
        day3_summary_md = fullfile(repo_root, 'results', 'recovery_mini', 'day3', 'day3_stage1_recovery_mini_summary.md');
    end

    assert(exist(candidate_ranking_csv, 'file') == 2, 'Day 3 candidate ranking CSV not found: %s', candidate_ranking_csv);
    assert(exist(day3_summary_md, 'file') == 2, 'Day 3 summary report not found: %s', day3_summary_md);

    ranking = readtable(candidate_ranking_csv, 'TextType', 'string');
    assert(any(ranking.candidate_id == "C1"), 'Day 3 ranking must contain C1.');

    room_types = ["A", "B", "C"];
    room_size = [5.0, 4.0, 3.0];
    anchor = [room_size(1) / 2.0, room_size(2) / 2.0, room_size(3) - 0.30];

    seed_stage_id = "stage2_recovery_room_mini_day4";
    seed_base = 20260424;
    label_rule = "mixed_0p33_primary";
    n_uniform_per_room = 90;

    rows = {};
    case_id = 0;
    for room_idx = 1:numel(room_types)
        room_type = room_types(room_idx);
        [grid_tbl, ~] = scenes.generateRoomTxRxGrid(char(room_type), room_size, n_uniform_per_room, double(seed_base + room_idx));

        for i = 1:height(grid_tbl)
            case_id = case_id + 1;
            [snr_db, xpol_db, eps_mult, wall_mat] = baselineParams(i);
            rows(end + 1, :) = makeRow(case_id, seed_stage_id, seed_base, room_type, ...
                grid_tbl.anchor_x(i), grid_tbl.anchor_y(i), grid_tbl.anchor_z(i), ...
                grid_tbl.tag_x(i), grid_tbl.tag_y(i), grid_tbl.tag_z(i), ...
                grid_tbl.grid_layer(i), snr_db, xpol_db, eps_mult, wall_mat, ...
                "BASE", "uniform_room_coverage", label_rule, ...
                "Layer1+2 baseline room coverage from generateRoomTxRxGrid", 1); %#ok<AGROW>
        end

        targeted = buildTargetedCasesForRoom(room_type, anchor, seed_stage_id, seed_base, label_rule);
        for i = 1:numel(targeted)
            case_id = case_id + 1;
            t = targeted(i);
            rows(end + 1, :) = makeRow(case_id, seed_stage_id, seed_base, room_type, ...
                anchor(1), anchor(2), anchor(3), ...
                t.tag_x, t.tag_y, t.tag_z, ...
                t.grid_layer, t.snr_db, t.xpol_coupling_db, t.eps_r_multiplier, t.dominant_wall_material, ...
                t.expected_candidate_id, t.expected_condition, label_rule, t.notes, t.replicate_id); %#ok<AGROW>
        end
    end

    cases = cell2table(rows, 'VariableNames', { ...
        'case_id', 'seed_stage_id', 'seed_base', 'stage_id', 'base_seed', ...
        'room_type', 'grid_layer', 'anchor_x', 'anchor_y', 'anchor_z', 'tag_x', 'tag_y', 'tag_z', ...
        'snr_db', 'xpol_coupling_db', 'eps_r_multiplier', 'dominant_wall_material', ...
        'expected_candidate_id', 'expected_condition', 'label_rule', 'notes', 'replicate_id', ...
        'antenna_type', 'material_name'});

    cases = addLosGeometryColumns(cases);
    cases = sortrows(cases, {'room_type', 'expected_candidate_id', 'grid_layer', 'snr_db', 'xpol_coupling_db', 'eps_r_multiplier'});
    cases.case_id = (1:height(cases)).';

    meta = struct();
    meta.seed_stage_id = seed_stage_id;
    meta.seed_base = seed_base;
    meta.total_cases = height(cases);
    meta.cases_per_room = countsBy(cases, 'room_type');
    meta.cases_per_candidate = countsBy(cases, 'expected_candidate_id');
    meta.input_candidate_ranking = string(candidate_ranking_csv);
    meta.input_day3_summary = string(day3_summary_md);
    meta.day3_top_candidate = ranking.candidate_id(1);
end

function row = makeRow(case_id, seed_stage_id, seed_base, room_type, anchor_x, anchor_y, anchor_z, tag_x, tag_y, tag_z, grid_layer, snr_db, xpol_db, eps_mult, wall_mat, candidate_id, condition_name, label_rule, notes, replicate_id)
    row = { ...
        case_id, string(seed_stage_id), double(seed_base), string(seed_stage_id), double(seed_base), ...
        string(room_type), double(grid_layer), ...
        double(anchor_x), double(anchor_y), double(anchor_z), ...
        double(tag_x), double(tag_y), double(tag_z), ...
        double(snr_db), double(xpol_db), double(eps_mult), string(wall_mat), ...
        string(candidate_id), string(condition_name), string(label_rule), string(notes), double(replicate_id), ...
        "patch_ffd", string(wall_mat)};
end

function [snr_db, xpol_db, eps_mult, wall_mat] = baselineParams(idx)
    snr_cycle = [15, 25, 35];
    xpol_cycle = [22, 30, 38];
    eps_cycle = [0.88, 1.00, 1.12];
    mat_cycle = ["drywall", "concrete", "brick", "glass", "wood"];
    snr_db = snr_cycle(mod(idx - 1, numel(snr_cycle)) + 1);
    xpol_db = xpol_cycle(mod(idx - 1, numel(xpol_cycle)) + 1);
    eps_mult = eps_cycle(mod(idx - 1, numel(eps_cycle)) + 1);
    wall_mat = mat_cycle(mod(idx - 1, numel(mat_cycle)) + 1);
end

function targeted = buildTargetedCasesForRoom(room_type, anchor, seed_stage_id, seed_base, label_rule) %#ok<INUSD>
    point_sets = targetedPointSets(room_type);
    defs = candidateDefinitions();
    targeted = struct('tag_x', {}, 'tag_y', {}, 'tag_z', {}, 'grid_layer', {}, 'snr_db', {}, 'xpol_coupling_db', {}, 'eps_r_multiplier', {}, ...
        'dominant_wall_material', {}, 'expected_candidate_id', {}, 'expected_condition', {}, 'notes', {}, 'replicate_id', {});
    idx = 0;
    for d = 1:numel(defs)
        def = defs(d);
        pts = point_sets.(char(def.point_key));
        for p = 1:size(pts, 1)
            for c = 1:size(def.param_table, 1)
                idx = idx + 1;
                targeted(idx).tag_x = pts(p, 1); %#ok<AGROW>
                targeted(idx).tag_y = pts(p, 2);
                targeted(idx).tag_z = pts(p, 3);
                targeted(idx).grid_layer = pts(p, 4);
                targeted(idx).snr_db = def.param_table(c, 1);
                targeted(idx).xpol_coupling_db = def.param_table(c, 2);
                targeted(idx).eps_r_multiplier = def.param_table(c, 3);
                targeted(idx).dominant_wall_material = def.material_cycle(c);
                targeted(idx).expected_candidate_id = def.candidate_id;
                targeted(idx).expected_condition = def.condition_name;
                targeted(idx).notes = sprintf('%s translated from Day3 %s in Room %s', def.note, def.day3_source, room_type);
                targeted(idx).replicate_id = 100 * d + 10 * p + c;
            end
        end
    end
end


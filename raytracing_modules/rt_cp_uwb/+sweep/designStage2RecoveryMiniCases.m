function cases = addLosGeometryColumns(cases)
    anchor = [cases.anchor_x, cases.anchor_y, cases.anchor_z];
    tag = [cases.tag_x, cases.tag_y, cases.tag_z];
    delta = tag - anchor;
    los_dist = sqrt(sum(delta.^2, 2));
    los_dir = delta ./ max(los_dist, 1e-12);
    anchor_bore = repmat([0, 0, -1], height(cases), 1);
    tag_bore = repmat([0, 0, 1], height(cases), 1);

    cases.los_distance_m = los_dist;
    cases.los_angle_from_anchor_bore_deg = acosd(clamp(sum(los_dir .* anchor_bore, 2)));
    cases.los_angle_from_tag_bore_deg = acosd(clamp(sum((-los_dir) .* tag_bore, 2)));
end

function y = clamp(x)
    y = min(max(double(x), -1.0), 1.0);
end

function tbl = countsBy(cases, var_name)
    values = string(cases.(var_name));
    [G, labels] = findgroups(values);
    counts = splitapply(@numel, cases.case_id, G);
    tbl = table(labels, counts, 'VariableNames', {var_name, 'case_count'});
end
